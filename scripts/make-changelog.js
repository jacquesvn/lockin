/* Generate CHANGELOG.md from the two sources that already exist.
 *
 * WHY GENERATED. A hand-written changelog drifts from what the app actually told people, and
 * then you have two accounts of the same release with no way to know which is true. WHATSNEW
 * in docs/index.html is the notes users genuinely saw in the app on update, and git tags are
 * when each version genuinely shipped. Deriving from both means the file cannot disagree with
 * either — and if a release is missing notes here, it is because it was missing them in the
 * app too, which is worth knowing rather than papering over.
 *
 *   node scripts/make-changelog.js [outfile]        (default: CHANGELOG.md)
 *   node scripts/make-changelog.js --check          (CI: fail if the file is stale)
 */
const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

const ROOT = path.join(__dirname, '..');
const REPO = 'https://github.com/jacquesvn/lockin';
const args = process.argv.slice(2);
const CHECK = args.indexOf('--check') >= 0;
const OUT = path.join(ROOT, args.filter((a) => !a.startsWith('--'))[0] || 'CHANGELOG.md');

/* ---- the notes the app actually showed ---- */
const html = fs.readFileSync(path.join(ROOT, 'docs', 'index.html'), 'utf8');
const block = html.slice(html.indexOf('var WHATSNEW={'), html.indexOf('\n  };', html.indexOf('var WHATSNEW={')));
const notes = {};
const entryRe = /"(\d+\.\d+\.\d+)"\s*:\s*\[([\s\S]*?)\]/g;
let m;
while ((m = entryRe.exec(block))) {
  notes[m[1]] = (m[2].match(/"((?:[^"\\]|\\.)*)"/g) || [])
    .map((s) => s.slice(1, -1).replace(/\\"/g, '"').replace(/\\\\/g, '\\'));
}

/* ---- when each version shipped ---- */
const tags = execSync('git for-each-ref --sort=-creatordate --format="%(refname:short)|%(creatordate:short)" refs/tags', { cwd: ROOT })
  .toString().trim().split('\n')
  .map((l) => { const [t, d] = l.replace(/"/g, '').split('|'); return { tag: t, ver: t.replace(/^v/, ''), date: d }; })
  .filter((t) => /^\d+\.\d+\.\d+$/.test(t.ver));

const cmp = (a, b) => {
  const x = a.split('.').map(Number), y = b.split('.').map(Number);
  for (let i = 0; i < 3; i++) if (x[i] !== y[i]) return x[i] - y[i];
  return 0;
};

/* ---- render ---- */
const documented = tags.filter((t) => notes[t.ver]);
const bare = tags.filter((t) => !notes[t.ver]);

let out = '';
out += '# Changelog\n\n';
out += 'Generated by `scripts/make-changelog.js` from two sources that cannot be quietly\n';
out += 'edited to flatter a release: the `WHATSNEW` notes users were actually shown in the app,\n';
out += 'and the git tag dates. Do not hand-edit — run the script.\n\n';
out += 'Full downloads and installers: [Releases](' + REPO + '/releases).\n\n';

documented.sort((a, b) => cmp(b.ver, a.ver)).forEach((t) => {
  out += '## [' + t.ver + '](' + REPO + '/releases/tag/' + t.tag + ') — ' + t.date + '\n\n';
  notes[t.ver].forEach((line) => { out += '- ' + line + '\n'; });
  out += '\n';
});

if (bare.length) {
  out += '## Earlier releases\n\n';
  out += 'In-app release notes began at 0.44.0. These ' + bare.length + ' earlier versions shipped\n';
  out += 'without them, so rather than invent notes after the fact, here is what is actually\n';
  out += 'known — the version and the day it shipped. The tag links to its release.\n\n';
  out += '| Version | Released |\n|---|---|\n';
  bare.sort((a, b) => cmp(b.ver, a.ver)).forEach((t) => {
    out += '| [' + t.ver + '](' + REPO + '/releases/tag/' + t.tag + ') | ' + t.date + ' |\n';
  });
  out += '\n';
}

/* ---- write, or verify ----
 * --check deliberately does NOT compare the whole file. The tag for the release being
 * prepared does not exist yet when CI runs on main, so an exact match would fail on every
 * release and pass only in between — a gate that fires when you are least able to act on it.
 * What it checks is the invariant that actually matters and does not depend on tag order:
 * every set of notes users were shown in the app must also be in the changelog. */
if (CHECK) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  const missing = Object.keys(notes).filter((v) => current.indexOf('[' + v + ']') < 0);
  if (missing.length) {
    console.error('✗ CHANGELOG.md is missing ' + missing.length + ' release(s) users were shown in-app: ' +
                  missing.join(', ') + '\n  run: node scripts/make-changelog.js');
    process.exit(1);
  }
  console.log('✓ every in-app release note is in CHANGELOG.md (' + Object.keys(notes).length + ' checked)');
} else {
  fs.writeFileSync(OUT, out);
  console.log('wrote ' + path.relative(ROOT, OUT) + ' — ' + documented.length + ' documented release(s), ' +
              bare.length + ' earlier, ' + tags.length + ' tags total');
  if (!documented.length) console.error('WARNING: no WHATSNEW entries matched a tag — check the parser');
}
